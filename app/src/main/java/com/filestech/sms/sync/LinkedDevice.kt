package com.filestech.sms.sync

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * What kind of device linked to this phone. The wire values
 * (`desktop`, `phone`, `tablet`) are fixed by SYNC_PROTOCOL.md — the QR
 * code and the `hello` message both carry them.
 */
@Serializable
enum class DeviceKind(val wire: String) {
    @SerialName("desktop")
    DESKTOP("desktop"),

    @SerialName("phone")
    PHONE("phone"),

    @SerialName("tablet")
    TABLET("tablet");

    companion object {
        fun fromWire(wire: String): DeviceKind? = entries.firstOrNull { it.wire == wire }
    }
}

/**
 * One linked device, as stored on the phone (see [LinkedDeviceStore]).
 * The public key is stored base64url, exactly as it arrived in the QR
 * code — it is a *public* key, so it needs no encryption at rest. The
 * matching private key never leaves the linked device.
 *
 * @property deviceId stable UUID generated by the linking device.
 * @property displayName the name the user confirmed at pairing time.
 * @property publicKeyBase64Url 32-byte Ed25519 public key, base64url, no padding.
 * @property linkedAt unix ms when the user confirmed the pairing.
 * @property lastSeen unix ms of the last authenticated contact, null if it never connected.
 */
@Serializable
data class LinkedDevice(
    @SerialName("device_id") val deviceId: String,
    @SerialName("kind") val kind: DeviceKind,
    @SerialName("display_name") val displayName: String,
    @SerialName("public_key") val publicKeyBase64Url: String,
    @SerialName("linked_at") val linkedAt: Long,
    @SerialName("last_seen") val lastSeen: Long? = null,
)
